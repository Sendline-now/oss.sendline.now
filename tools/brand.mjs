import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { Resvg } from '@resvg/resvg-js';

import { lockupWidth, markBody, markGap, marks, patch, sendlineMark, sendlineSmall, smallBody, wordBody, wordWidth } from './lib/marks.mjs';

const out = 'brand';

const ground = { dark: '#0c0d0f', light: '#f7f5f0' };
const ink = { dark: '#f1f0ec', light: '#16130e' };

const svg = (comment, viewBox, label, body) => `<!--
  ${comment}
  Generated by tools/brand.mjs in Sendline-now/oss.sendline.now. Change the source there and regenerate; do not edit
  this file by hand.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-label="${label}">
  ${body}
</svg>
`;

const files = (id, mark) => {
  const width = lockupWidth(mark.word);
  const wordOnly = wordWidth(mark.word) + 8;
  const group = `<g id="mark" aria-label="${id} mark">
    ${markBody(mark)}
  </g>`;
  const lockup = (letters) => `${group}\n  ${wordBody(mark.word, letters, mark.colour, markGap, 31, { id: 'wordmark' })}`;

  return {
    [`${id}.svg`]: svg(
      `${id}.svg — the full lockup, mark and wordmark. The letters take currentColor, so this one is for pages that set
  a text colour; a README needs ${id}-light.svg and ${id}-dark.svg, because an <img> has no text colour to give.`,
      `0 0 ${width} 120`, id, lockup('currentColor')),
    [`${id}-light.svg`]: svg(`${id}-light.svg — the full lockup for a light background: dark letters.`,
      `0 0 ${width} 120`, id, lockup(ink.light)),
    [`${id}-dark.svg`]: svg(`${id}-dark.svg — the full lockup for a dark background: light letters.`,
      `0 0 ${width} 120`, id, lockup(ink.dark)),
    [`${id}-mark.svg`]: svg(`${id}-mark.svg — the mark alone: an avatar, a tab, anywhere the name stands beside it.`,
      '0 0 120 120', `${id} mark`, group),
    [`${id}-wordmark.svg`]: svg(
      `${id}-wordmark.svg — the wordmark alone, letters in currentColor, for where the mark is already on screen.`,
      `0 0 ${wordOnly} 78`, id, wordBody(mark.word, 'currentColor', mark.colour, 4, 4, { id: 'wordmark' })),
    [`${id}-favicon.svg`]: svg(
      `${id}-favicon.svg — the mark retold for sixteen pixels: no inner contour, a heavier glyph with fewer strokes.`,
      '0 0 120 120', `${id} mark, small`, `<g id="mark-small" aria-label="${id} mark, small">
    ${smallBody(mark)}
  </g>`),
  };
};

const social = (mark) => {
  const scale = 2;
  const x = (1280 - lockupWidth(mark.word) * scale) / 2;

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1280 640" width="1280" height="640">
  <rect width="1280" height="640" fill="${ground.dark}"/>
  <g transform="translate(940 330) scale(4.2)" opacity="0.07"><path fill="${mark.colour}" d="${patch}"/></g>
  <g transform="translate(${x} 170) scale(${scale})">
  ${markBody(mark)}
  ${wordBody(mark.word, ink.dark, mark.colour, markGap, 31)}
  </g>
  <path stroke="#272a2e" stroke-width="2" d="M80 520 H1200"/>
  <g transform="translate(80 548) scale(0.42)">
  ${sendlineMark()}
  ${wordBody('SENDLINE', '#959aa1', '#959aa1', markGap, 31, { rule: false })}
  </g>
</svg>`;
};

const png = (source, width) =>
  new Resvg(source, { fitTo: { mode: 'width', value: width }, background: 'rgba(0,0,0,0)' }).render().asPng();

const strip = (source) => source.replace(/<!--[\s\S]*?-->\s*/, '');

// The house mark itself, in the orange the sendline.now header wears (web/app/components/BrandLogo.vue), for the
// site's own header and tab. The geometry is BRAND.md's, unchanged.
await mkdir(out, { recursive: true });
await writeFile(join(out, 'sendline-mark.svg'), svg(
  'sendline-mark.svg — the Sendline mark from sendline.now design/logos/chosen, in the header orange.',
  '0 0 120 120', 'Sendline mark', `<g id="sendline-mark">
    ${sendlineMark()}
  </g>`));
await writeFile(join(out, 'sendline-favicon.svg'), svg(
  'sendline-favicon.svg — the Sendline sixteen-pixel mark from sendline.now design/logos/chosen, in the header orange.',
  '0 0 120 120', 'Sendline mark, small', sendlineSmall()));

for (const [id, mark] of Object.entries(marks)) {
  const dir = join(out, id);
  await mkdir(dir, { recursive: true });

  const generated = files(id, mark);
  for (const [name, content] of Object.entries(generated)) await writeFile(join(dir, name), content);

  await writeFile(join(dir, `${id}-mark-512.png`), png(strip(generated[`${id}-mark.svg`]), 512));
  await writeFile(join(dir, `${id}-dark-1200.png`), png(strip(generated[`${id}-dark.svg`]), 1200));
  await writeFile(join(dir, `${id}-light-1200.png`), png(strip(generated[`${id}-light.svg`]), 1200));
  await writeFile(join(dir, `${id}-social.png`), png(social(mark), 1280));

  console.log(`${id}: ${Object.keys(generated).length} svg, 4 png`);
}
